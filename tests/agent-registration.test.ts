import assert from 'node:assert/strict';
import { SampleWorkdeckDataSource } from '../src/data/repository';
import { createHttpDataSource } from '../src/data/httpRepository';
import { createSampleSnapshot } from '../src/data/fixtures';
import type { Snapshot } from '../src/data/types';

(async () => {
  const source = new SampleWorkdeckDataSource();
  let snapshot: Snapshot = await source.load();
  source.subscribe(value => { snapshot = value; });
  const first = await source.createIdea('我要去芭提雅');
  const historical = await source.createIdea('已有交通方案');
  await source.recordDiscussionConclusion(historical.planId, 'root', { agentId: 'claude', summary: '先比较交通', confirmed: ['坐飞机'], open: [] });
  const sessions = structuredClone(snapshot.sessions);
  const tasks = structuredClone(snapshot.tasks);
  const oldConclusion = structuredClone(snapshot.ideaPlans![historical.planId].discussion!.conclusions[0]);
  const registration = { id: 'cursor', name: 'Cursor', short: 'Cursor', color: '#6e6d8a' };
  assert.equal((await source.registerAgent(registration)).ok, true);
  const cursor = snapshot.agents.find(agent => agent.id === 'cursor')!;
  assert.ok(cursor.registered);
  assert.equal(cursor.connection, 'offline', 'registration is not a verified live connection');
  assert.equal(cursor.today.tokens, null);
  assert.equal(snapshot.defaultAgent, 'cursor', 'first configured tool becomes default');
  assert.equal(snapshot.ideaPlans![first.planId].discussion!.agentId, 'cursor', 'empty existing plan receives matching discussion identity');
  assert.equal(snapshot.ideaPlans![historical.planId].discussion!.agentId, 'claude', 'historical plan is not silently retargeted');
  assert.deepEqual(snapshot.ideaPlans![historical.planId].discussion!.conclusions[0], oldConclusion, 'historical attribution is unchanged');
  assert.deepEqual(snapshot.sessions, sessions, 'registration creates no sessions and retains running data');
  assert.deepEqual(snapshot.tasks, tasks, 'registration retains existing tasks');
  await source.registerAgent(registration);
  assert.equal(snapshot.agents.filter(agent => agent.id === 'cursor').length, 1, 'repeat saves do not duplicate identity');
  const next = await source.createIdea('另一段旅行');
  assert.equal(snapshot.ideaPlans![next.planId].discussion!.agentId, 'cursor');
  assert.equal((await source.setDiscussionAgent(next.planId, 'cursor')).ok, true, 'registered Cursor is accepted by business commands');
  await source.recordDiscussionConclusion(next.planId, 'root', { agentId: 'cursor', summary: '安排五天', confirmed: ['五天四晚'], open: [] });
  assert.equal(snapshot.ideaPlans![next.planId].discussion!.conclusions.at(-1)!.agentId, 'cursor');
  await source.registerAgent({id: 'opencode', name: 'OpenCode', short: 'OpenCode', color: '#527b6b'});
  await source.setDiscussionAgent(next.planId, 'opencode');
  await source.recordDiscussionConclusion(next.planId, 'root', { agentId: 'cursor', summary: '之前 Cursor 讨论的补充', confirmed: [], open: [] });
  assert.equal(snapshot.ideaPlans![next.planId].discussion!.agentId, 'opencode');
  assert.equal(snapshot.ideaPlans![next.planId].discussion!.conclusions.at(-1)!.agentId, 'cursor', 'open record dialog preserves explicit source when target changes');
  const count = snapshot.ideaPlans![next.planId].discussion!.conclusions.length;
  assert.equal((await source.recordDiscussionConclusion(next.planId, 'root', { agentId: 'unknown', summary: '拒绝未知来源', confirmed: [], open: [] })).ok, false);
  assert.equal(snapshot.ideaPlans![next.planId].discussion!.conclusions.length, count);
  assert.equal((await source.registerAgent({...registration, id: '../invalid'})).ok, false);
  const codexBefore = structuredClone(snapshot.agents.find(agent => agent.id === 'codex'));
  await source.registerAgent({id: 'codex', name: 'Codex', short: 'Codex', color: '#527f9e'});
  assert.deepEqual(snapshot.agents.find(agent => agent.id === 'codex'), {...codexBefore, registered: true}, 'existing tool stats and identity are not overwritten');

  let request: {url:string; body:unknown} | null = null;
  globalThis.fetch = async (url, init) => {
    request = { url: String(url), body: JSON.parse(init?.body as string) };
    return Response.json({revision: 1, snapshot: createSampleSnapshot(), result: {ok: true, agentId: 'cursor'}});
  };
  const http = createHttpDataSource('http://localhost:9000');
  const result = await http.registerAgent(registration);
  assert.equal(result.agentId, 'cursor');
  assert.match(request!.url, /\/v1\/commands\/registerAgent$/);
  assert.deepEqual((request!.body as any).args, [registration]);
  console.log('Agent registration: identity, idempotency, default/plan alignment, existing records, explicit conclusion attribution and HTTP contract passed.');
  process.exit(0);
})().catch(error => { console.error(error); process.exit(1); });
