import assert from 'node:assert/strict';
import { createDeliveryFixture } from './delivery-map.fixture';
import { LocalWorkdeckDataSource } from '../src/data/repository';
import { deriveDeliveryMap } from '../src/data/goalDelivery';
import { deliveryReview, deliveryReviewCommand } from '../src/data/deliveryReview';
const storage = new Map<string,string>();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(key:string)=>storage.get(key)??null,setItem:(key:string,value:string)=>storage.set(key,value),removeItem:(key:string)=>storage.delete(key)}});
async function main() {
  await createDeliveryFixture(); const api=new LocalWorkdeckDataSource();
  let snapshot=await api.load();
  const slot=deriveDeliveryMap(snapshot).slots.find(slot=>slot.state==='candidate')!, artifactId=slot.artifact!.id;
  let view=deliveryReview(snapshot,artifactId)!;
  assert(view.reviewable);assert(view.task.workItemId,'fixture is an actual child task');
  assert.throws(()=>deliveryReviewCommand(snapshot,artifactId,'accepted',view.spec!.criteria.map(()=>false),'not checked'),/逐条确认/);
  assert.throws(()=>deliveryReviewCommand(snapshot,artifactId,'accepted',view.spec!.criteria.map(()=>true),''),/说明/);
  const stale=structuredClone(snapshot);stale.collaboration!.artifacts.find(a=>a.id===artifactId)!.expiresAt='2000-01-01T00:00:00.000Z';
  assert(!deliveryReview(stale,artifactId)!.fresh);
  assert.throws(()=>deliveryReviewCommand(stale,artifactId,'accepted',view.spec!.criteria.map(()=>true),'checked'),/失效/);
  assert.equal(deliveryReviewCommand(stale,artifactId,'needs_changes',view.spec!.criteria.map(()=>false),'refresh source').payload!.verdict,'needs_changes');
  const mismatched=structuredClone(snapshot);mismatched.collaboration!.submissions.find(s=>s.id===view.submission!.id)!.specRevision++;
  assert(!deliveryReview(mismatched,artifactId)!.reviewable);
  const command=deliveryReviewCommand(snapshot,artifactId,'accepted',view.spec!.criteria.map(()=>true),'逐条对照正文与来源，确认符合要求');
  assert.equal(command.taskId,slot.taskId);assert.equal(command.workItemId,slot.workItemId);
  const accepted=await api.collaborate(command);assert(accepted.ok,accepted.message);
  snapshot=await api.load();assert(deliveryReview(snapshot,artifactId)!.accepted);
  assert.equal(snapshot.collaboration!.tasks[slot.taskKey].status,'done');
  assert.notEqual(snapshot.collaboration!.tasks[slot.taskId].status,'done','reviewing child never completes parent');
  const reviews=snapshot.collaboration!.reviews.length;
  assert((await api.collaborate(command)).ok,'same command is idempotent');
  assert.equal((await api.load()).collaboration!.reviews.length,reviews);
  const task=(await api.createTaskWithAttachments('当前候选版本',[],snapshot.project.id)).taskId!;
  await api.saveTaskOutput({taskId:task,title:'第一稿',body:'第一版真实正文',status:'published'});
  snapshot=await api.load();let record=snapshot.collaboration!.tasks[task];
  const original=snapshot.collaboration!.submissions.find(s=>s.id===record.latestSubmissionId)!.artifactId;
  view=deliveryReview(snapshot,original)!;
  const oldCommand=deliveryReviewCommand(snapshot,original,'accepted',view.spec!.criteria.map(()=>true),'旧版已核对');
  await api.saveTaskOutput({taskId:task,title:'第二稿',body:'新的正文',status:'published'});
  assert(!(await api.collaborate(oldCommand)).ok,'version CAS rejects outdated review');
  snapshot=await api.load();assert(!deliveryReview(snapshot,original)!.reviewable);
  record=snapshot.collaboration!.tasks[task];const current=snapshot.collaboration!.submissions.find(s=>s.id===record.latestSubmissionId)!.artifactId;
  view=deliveryReview(snapshot,current)!;
  const returned=await api.collaborate(deliveryReviewCommand(snapshot,current,'needs_changes',view.spec!.criteria.map(()=>false),'补齐具体来源'));assert(returned.ok,returned.message);
  snapshot=await api.load();assert.equal(snapshot.collaboration!.tasks[task].status,'ready');assert.equal(snapshot.collaboration!.reviews.at(-1)!.note,'补齐具体来源');
  console.log('Delivery review: exact child scope, criteria/note, freshness, current submission, spec/version guard, return and idempotence passed');
}
void main();
