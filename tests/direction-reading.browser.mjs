import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// Run against the isolated preview, with an explicitly provided Playwright install.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const base = process.env.PREVIEW_URL ?? 'http://127.0.0.1:4316';
const output = process.env.EVIDENCE_DIR ?? '/tmp/quandeck-direction-reading';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const errors = [], checks = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
const goto = async (query = '') => { await page.goto(`${base}/tests/direction-reading.preview.html${query}`); await page.getByLabel('切换正文版本').waitFor(); };
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
const visible = selector => page.locator(selector).isVisible();
try {
  await goto();
  for (const width of [320, 390, 768, 1000, 1001, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.waitForFunction(expected => document.querySelector('.qd-ws')?.dataset.discussionNarrow === String(expected), width <= 1000);
    check(`layout ${width}: no page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check(`layout ${width}: document remains visible`, await visible('.qd-ws-main'));
    check(`layout ${width}: correct discussion layout`, await visible('.qd-ws-side') === (width > 1000));
    if ([320, 1440].includes(width)) await page.screenshot({ path: `${output}/direction-reading-${width}.png` });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const widthBefore = await page.locator('.qd-ws-main').evaluate(node => node.clientWidth);
  await page.getByRole('button', { name: '收起讨论', exact: true }).click();
  check('desktop sidebar collapses', !await visible('.qd-ws-side'));
  check('desktop document expands', await page.locator('.qd-ws-main').evaluate(node => node.clientWidth) > widthBefore);
  await page.getByRole('button', { name: '讨论这一节', exact: true }).first().click();
  check('section discussion reopens sidebar', await visible('.qd-ws-side'));
  await page.getByRole('button', { name: '查看整体结论', exact: true }).click();
  const version = page.getByLabel('切换正文版本');
  await version.focus(); await version.selectOption('adopted');
  check('body version selector keeps focus', await version.evaluate(node => document.activeElement === node));
  check('saved body displayed', await page.getByText('确认快照：只支持标题检索，保留原验收范围。', { exact: true }).isVisible());
  check('draft body hidden in saved view', !await page.getByText('当前草稿：增加正文与书摘检索，等待新的方向确认。', { exact: true }).isVisible());
  check('saved version has no mutation or execution controls', await page.locator('.qd-ws-main').getByRole('button', { name: /确认方向|编辑大纲|查看任务拆分|讨论这一节|补充这部分/ }).count() === 0);
  check('saved version has no current revision action', await page.getByRole('button', { name: '查看任务影响' }).count() === 0);
  await page.getByLabel('查看结论记录').selectOption('search-method-discussion');
  check('discussion history does not switch document version', await version.inputValue() === 'adopted');
  await page.screenshot({ path: `${output}/direction-reading-confirmed-1440.png` });
  await page.getByRole('button', { name: '阅读方案正文' }).click();
  check('reading current discussion returns to draft', await version.inputValue() === 'draft');
  await page.setViewportSize({ width: 390, height: 844 });
  const toggle = page.locator('.qd-discussion-toggle');
  await toggle.click();
  const drawer = page.getByRole('dialog', { name: '讨论与版本', exact: true });
  await drawer.waitFor();
  check('drawer starts at close control', await page.getByRole('button', { name: '关闭讨论', exact: true }).evaluate(node => document.activeElement === node));
  check('document remains behind modal', await visible('.qd-ws-main'));
  await page.keyboard.press('Shift+Tab');
  check('drawer backward focus is contained', await drawer.evaluate(node => node.contains(document.activeElement)));
  await page.keyboard.press('Tab');
  check('drawer forward focus wraps', await page.getByRole('button', { name: '关闭讨论', exact: true }).evaluate(node => document.activeElement === node));
  await page.getByRole('button', { name: '查看本轮方案详情', exact: true }).click();
  await page.getByRole('dialog', { name: '方案详情', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  check('nested detail Escape keeps discussion open', await drawer.isVisible());
  check('nested detail focus restored', await page.getByRole('button', { name: '查看本轮方案详情', exact: true }).evaluate(node => document.activeElement === node));
  await page.screenshot({ path: `${output}/direction-reading-drawer-390.png` });
  await page.keyboard.press('Escape');
  check('drawer Escape closes modal', !await drawer.isVisible());
  check('drawer focus restored to opening button', await toggle.evaluate(node => document.activeElement === node));
  await toggle.click(); await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForFunction(() => document.querySelector('.qd-ws')?.dataset.discussionNarrow === 'false');
  check('resize removes drawer and displays desktop sidebar', await drawer.count() === 0 && await visible('.qd-ws-side'));
  await goto('?container=900');
  check('wide window narrow workspace uses drawer', await page.locator('.qd-ws').getAttribute('data-discussion-narrow') === 'true');
  await goto('?fault=agent');
  const agent = page.getByLabel('选择讨论 Agent');
  const previousAgent = await agent.inputValue();
  await agent.selectOption('codex');
  check('agent selection locks while saving', await agent.isDisabled());
  await page.getByRole('alert').filter({ hasText: '讨论目标保存失败' }).waitFor();
  check('agent failure preserves actual saved selection', await agent.inputValue() === previousAgent && !await agent.isDisabled());
  await agent.selectOption('codex');
  await page.getByRole('alert').filter({ hasText: '讨论目标保存失败' }).waitFor();
  check('agent failure is retryable', !await agent.isDisabled());
  await goto('?fault=split');
  await page.getByRole('button', { name: '查看任务拆分', exact: true }).click();
  check('split locks while reading', await page.getByRole('button', { name: '正在读取拆分…' }).isDisabled());
  await page.getByRole('alert').filter({ hasText: '拆分草稿读取失败' }).waitFor();
  check('split failure keeps document and retry', await visible('.qd-direction-doc') && await page.getByRole('button', { name: '查看任务拆分', exact: true }).isEnabled());
  await goto('?fault=attachment');
  await page.getByRole('button', { name: '附件 1', exact: true }).click();
  const attachment = page.getByRole('dialog', { name: '任务附件', exact: true });
  await attachment.getByTitle('下载 验收说明.pdf').click();
  await attachment.getByRole('button', { name: '重试下载 验收说明.pdf' }).waitFor();
  check('missing attachment download offers retry', await attachment.getByRole('alert').isVisible());
  await attachment.getByRole('button', { name: '重试下载 验收说明.pdf' }).click();
  await attachment.getByRole('button', { name: '重试下载 验收说明.pdf' }).waitFor();
  await attachment.getByLabel('上传任务附件').setInputFiles({ name: '隔离上传.txt', mimeType: 'text/plain', buffer: Buffer.from('fixture only') });
  await attachment.getByRole('alert').filter({ hasText: '附件关联失败' }).waitFor();
  check('failed attachment association retains old attachment', await attachment.getByTitle('下载 验收说明.pdf').isVisible());
  const keys = await page.evaluate(() => new Promise(resolve => { const request = indexedDB.open('quandeck-output-files'); request.onsuccess = () => { const db = request.result, tx = db.transaction('files'), keys = tx.objectStore('files').getAllKeys(); tx.oncomplete = () => { resolve(keys.result); db.close(); }; }; }));
  check('failed attachment association removes newly stored bytes', keys.length === 0);
  check('no unhandled page errors', errors.length === 0);
  console.log(JSON.stringify({ checks: checks.length, passed: checks, errors }, null, 2));
} finally {
  await writeFile(`${output}/direction-reading-ui-results.json`, JSON.stringify({ checks, errors }, null, 2));
  await browser.close();
}
