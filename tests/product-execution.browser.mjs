import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.QUANDECK_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.QUANDECK_UI_URL || 'http://127.0.0.1:4321';
const output = process.env.QUANDECK_UI_OUTPUT || 'output/product/execution-browser';
await mkdir(output,{recursive:true});
const browser = await chromium.launch({headless:true,channel:'chrome'});
const context = await browser.newContext({storageState:{cookies:[],origins:[]}, viewport:{width:1440,height:900}});
const page = await context.newPage();
const errors=[];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*',route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
try {
  await page.goto(origin);
  const nav = name => page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name,exact:true});
  await nav('帮你盯').click();
  await page.getByText('现在没有需要你处理的事。').waitFor();
  const target = await page.evaluate(async () => {
    if (window.quandeckDesktop) throw Error('Browser tests must not write through the desktop bridge.');
    const {localDataSource:api}=await import('/src/data/repository.ts');
    if ((await api.listProjects()).length) throw Error('Expected a fresh isolated browser context.');
    const projectId=(await api.createProject({name:'项目 · 分派验收'})).projectId;
    const taskId=(await api.createTaskWithAttachments('【领导交办】制作页面预览',[],projectId)).taskId;
    await api.setTaskOwner(taskId,'agent');
    const planning=await api.updateProjectPlanning(projectId,{kind:'task',taskId,expectedRevision:0,fields:{end:'2020-01-01',information:'预览图请注明测试场景'}});
    if (!planning.ok) throw Error(planning.message);
    return {projectId,taskId};
  });
  await page.reload();
  await nav('帮你管').waitFor();
  const dialog=page.getByRole('dialog',{name:'分派任务'});
  const dispatch=() => page.evaluate(target => window.dispatchEvent(new CustomEvent('quandeck:drag-task',{detail:target})),target);
  const current=() => page.evaluate(async target => {
    const {readProjectLibrary}=await import('/src/data/projectStorage.ts');
    const snapshot=readProjectLibrary().projects[target.projectId];
    return {owner:snapshot.tasks[target.taskId].owner,sessions:Object.keys(snapshot.sessions).length};
  },target);
  await dispatch();
  const dock=page.locator('[data-product-dock]');
  await dock.getByRole('button',{name:'我 自己处理'}).click();
  await dialog.waitFor();
  assert.deepEqual(await current(),{owner:'agent',sessions:0},'drag alone never starts an execution');
  await dialog.getByText(/查看随任务发送的资料/).click();
  await dialog.getByText('预览图请注明测试场景',{exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'dispatch-confirmation.png'),animations:'disabled'});
  await dialog.getByRole('button',{name:'取消'}).click();
  await dialog.waitFor({state:'hidden'});
  assert.deepEqual(await current(),{owner:'agent',sessions:0},'cancel makes no change');
  await dispatch();
  await dock.getByRole('button',{name:'我 自己处理'}).click();
  await dialog.getByRole('button',{name:'确认由我处理'}).click();
  await dialog.waitFor({state:'hidden'});
  assert.deepEqual(await current(),{owner:'me',sessions:0},'only explicit confirmation changes assignment');
  await nav('帮你盯').click();
  const card=page.locator('.qd-product-monitor-card').filter({hasText:'制作页面预览'});
  await card.getByText(/领导交办/).first().waitFor();
  await page.screenshot({path:path.join(output,'monitor.png'),animations:'disabled'});
  await card.getByText('提醒选项').click();
  await card.getByRole('button',{name:'明天提醒'}).click();
  await card.waitFor({state:'hidden'});
  await page.getByText('已处理的提醒（1 项）').click();
  await page.getByRole('button',{name:'恢复',exact:true}).click();
  await card.waitFor();
  assert.deepEqual(errors,[]);
  console.log('product execution: empty monitor, temporary dock, exact task materials, cancellation, confirmed assignment, reminder defer and restore');
} finally {await browser.close();}
