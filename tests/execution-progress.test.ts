import assert from 'node:assert/strict';
import { executionProgress, executionStage, sessionProgress } from '../src/data/executionProgress';
import { deriveProjectActivity } from '../src/data/projectActivity';
import { createEmptySnapshot } from '../src/data/projectStorage';
import type { Session, WorkStatus } from '../src/data/types';
import { taskReplyTargets } from '../src/data/taskInput';
import { taskExecutionPresentation } from '../src/data/taskExecutionPresentation';

const run: Session = { id: 'run', agentId: 'codex', title: '生成攻略', taskId: null, origin: 'dispatch', status: 'running', startedAt: '2026-11-16T12:00:00Z', lastActivity: '2026-11-16T12:00:00Z', step: null, tokens: 999999, rounds: [], subAgents: [] };
const unknown = sessionProgress(run)!;
assert.equal(unknown.state, 'flowing');
assert.equal(unknown.mode, 'unknown');
assert.equal(unknown.value, undefined, 'elapsed activity/token usage never invents a percentage');
assert.equal(executionProgress('submitting')!.label, '正在发送任务');
assert.equal(executionProgress('queued')!.state, 'queued');
assert.equal(executionProgress('waiting_reply')!.state, 'paused', 'waiting without source steps still has visible progress');
assert.equal(executionProgress('waiting_reply')!.value, undefined);
assert.equal(executionProgress('waiting_permission')!.label, '等待你的授权');
assert.equal(executionProgress('failed')!.state, 'stopped');
assert.equal(executionProgress('paused')!.state, 'paused');
assert.equal(executionProgress('archived'), null);
assert.equal(executionProgress('cancelled'), null);

run.step = { total: 8, completed: 3, label: '整理住宿信息' };
let progress = sessionProgress(run)!;
assert.equal(progress.mode, 'steps'); assert.equal(progress.value, 3); assert.equal(progress.total, 8);
assert.equal(progress.amount, '本轮已完成 3/8 步');
assert.equal(progress.stage, '整理住宿信息');
assert.equal(executionProgress('waiting_reply', { total: 8, completed: 8, label: '已完成' })!.label, '等待你的回复', 'a completed round never accepts the task');
for (const step of [{total: 8, label: 'incomplete'}, {total: NaN, completed: 1, label: 'bad'}, {total: 3, completed: 4, label: 'overflow'}, {total: 3.5, completed: 1, label: 'fraction'}, {total: 4, completed: -1, label: 'negative'}]) {
  assert.equal(executionProgress('running', step)!.mode, 'unknown', 'invalid or absent completion evidence is never treated as a number');
}
for (const percent of [NaN, Infinity, -1, 101]) assert.equal(executionProgress('running', null, percent)!.mode, 'unknown');
assert.equal(executionProgress('running', null, 0)!.value, 0, 'zero is real source progress');
assert.equal(executionProgress('running', null, 68.5)!.value, 68.5);
assert.equal(executionStage("/bin/zsh -lc 'python3 /tmp/verify_thailand_guide.py'"), '正在运行任务工具');
assert.equal(executionStage('npm test'), '正在运行任务工具');
assert.equal(executionStage('正在核对酒店照片'), '正在核对酒店照片');
run.step = { label: '/bin/zsh -lc command' };
assert.equal(sessionProgress(run)!.stage, '正在运行任务工具');
run.status = 'waiting_reply';
assert.equal(sessionProgress(run)!.stage, '', 'stale last command is not shown as current waiting work');

const snapshot = createEmptySnapshot();
snapshot.sessions[run.id] = { ...run, status: 'running', step: { total: 5, completed: 2, label: '核对地图' } };
const entry = deriveProjectActivity(snapshot).entries[0];
assert.equal(entry.step?.completed, 2); assert.equal(entry.step?.total, 5);
assert.deepEqual(executionProgress(entry.state, entry.step, entry.percent), sessionProgress(snapshot.sessions[run.id]), 'task and activity progress use identical source facts');
const before = JSON.stringify(snapshot);
executionProgress(entry.state, entry.step, entry.percent);
assert.equal(JSON.stringify(snapshot), before, 'progress presentation never modifies source or task completion');
console.log('Execution progress: real counts, unknown totals, dispatch/wait/failure states, command privacy and cross-view consistency passed');

// Parent-session history must never mask an active child execution in the task row.
const scoped = createEmptySnapshot();
scoped.tasks.t = { id:'t', title:'查询路线并补齐', createdAt:'2026-11-17T01:00:00Z', sessionIds:['parent'], completion:null, manualLock:true };
scoped.sessions.parent = { ...run, id:'parent', taskId:'t', status:'paused', lastActivity:'2026-11-17T03:00:00Z', rounds:[{id:'parent-round',at:'03:00',reply:'旧父会话摘要'}] };
scoped.orchestrations = { t:{ taskId:'t', label:'查询路线并补齐', mainSessionId:'parent', mainAgentId:'codex', startedAt:'01:00', syncedAt:'02:00', coordinationTokens:null, phases:[], executors:{ codex:{id:'codex',label:'Codex',agentId:'codex',parentExecutorId:null}}, items:{}, itemOrder:[], attempts:{}, capabilities:{subAgents:true,steps:true,tokens:false,permissionEvents:true} } };
const tree=scoped.orchestrations.t;
function child(id:string,status:WorkStatus,at:string,reply:string) {
  tree.items[id]={id,rootTaskId:'t',parentTaskId:'t',title:`子任务 ${id}`,phase:'查询',dependsOnTaskIds:[],owner:'agent',executorId:'codex',status,attemptIds:[`a-${id}`]};tree.itemOrder.push(id);
  tree.attempts[`a-${id}`]={id:`a-${id}`,workItemId:id,executorId:'codex',sessionId:`s-${id}`,parentSessionId:'parent',sourceLink:'',kind:'initial',status:'running',startedAt:at,tokens:null,step:{total:4,completed:1,label:`处理 ${id}`},rounds:[]};
  scoped.sessions[`s-${id}`]={...run,id:`s-${id}`,taskId:'t',status:status as Session['status'],lastActivity:at,rounds:reply?[{id:`r-${id}`,at,reply}]:[],step:{total:4,completed:1,label:`处理 ${id}`}};
}
child('地图','running','2026-11-17T02:00:00Z','子任务地图已核对');
for (const session of Object.values(scoped.sessions)) session.runtime={runId:session.id,dispatchId:session.id,projectId:scoped.project.id,taskId:'t',connection:{tool:'codex',connectionId:'c',projectPath:'/test'},purpose:'execution',context:{taskTitle:session.title,prompt:'test',capturedAt:'2026-11-17T01:00:00Z'},sequence:1,eventIds:[]};
assert.deepEqual(taskReplyTargets(scoped,'t'),[],'running child must not send new context to a paused parent');
let scopeView=taskExecutionPresentation(scoped,'t');
assert.equal(scopeView.hasChildActivity,true);
assert.deepEqual(scopeView.rows.map(row=>row.sessionId),['s-地图']);
assert.equal(scopeView.rows[0].progress?.label,'正在执行');
assert.equal(scopeView.primarySession?.id,'s-地图','a more recently touched paused parent cannot take over source navigation');
assert.equal(scopeView.primarySession?.rounds.at(-1)?.reply,'子任务地图已核对','reply and navigation use the same child source');
assert.deepEqual(scopeView.rows[0].progress,executionProgress(deriveProjectActivity(scoped).entries[0].state,deriveProjectActivity(scoped).entries[0].step,deriveProjectActivity(scoped).entries[0].percent),'inline and rail share the authoritative projection');
child('酒店','waiting_permission','2026-11-17T02:30:00Z','等待照片下载授权');
scopeView=taskExecutionPresentation(scoped,'t');
assert.equal(scopeView.rows.length,2,'parallel child progress remains independently visible');
assert(scopeView.rows.some(row=>row.progress?.label==='等待你的授权'),'permission waits do not fall back to parent history');
assert.equal(scopeView.primarySession?.id,'s-酒店');
assert.equal(scopeView.primaryTitle,'子任务 酒店');
assert.equal(scopeView.primarySession?.rounds.at(-1)?.reply,'等待照片下载授权');
scoped.sessions['s-酒店'].runtime={...scoped.sessions.parent.runtime!,runId:'s-酒店',workItemId:'酒店'};
assert.deepEqual(taskReplyTargets(scoped,'t'),[],'permission-waiting child cannot fall back to the old paused parent');
scoped.sessions['s-地图'].status='waiting_reply';tree.items['地图'].status='waiting_reply';
assert.deepEqual(taskReplyTargets(scoped,'t').map(session=>session.id),['s-地图'],'only the currently replyable child is offered');
scoped.sessions['s-酒店'].status='waiting_reply';tree.items['酒店'].status='waiting_reply';
assert.equal(taskReplyTargets(scoped,'t').length,2,'parallel replyable children remain selectable');
scoped.sessions['s-地图'].status='running';tree.items['地图'].status='running';
scoped.sessions['s-酒店'].status='waiting_permission';tree.items['酒店'].status='waiting_permission';
scoped.sessions['s-酒店'].rounds=[];
assert.equal(taskExecutionPresentation(scoped,'t').primarySession?.rounds.length,0,'no child reply means no parent reply is relabeled as current');
for(const item of Object.values(tree.items))item.status='paused';
scopeView=taskExecutionPresentation(scoped,'t');
assert.equal(scopeView.hasChildActivity,false);
assert.equal(scopeView.primarySession?.id,'parent','without active child activity, root-only behavior is retained');
assert.equal(scopeView.rows[0].progress?.label,'已暂停');
assert.deepEqual(taskReplyTargets(scoped,'t').map(session=>session.id),['parent'],'root-only reply remains available when there is no active child');
scoped.sessions.parent.status='archived';scoped.tasks.t.completion={reason:'manual',at:'03:30'};
scopeView=taskExecutionPresentation(scoped,'t');
assert.equal(scopeView.rows.length,0);
assert.equal(scopeView.primarySession?.id,'parent','completed parent retains its historical source link');
tree.items['地图'].status='queued';delete scoped.sessions['s-地图'];
scopeView=taskExecutionPresentation(scoped,'t');
assert.equal(scopeView.hasChildActivity,true);
assert.equal(scopeView.primarySession,undefined,'unacknowledged child has no invented source session');
assert.equal(scopeView.rows[0].progress?.mode,'steps');
const scopedBefore=JSON.stringify(scoped);taskExecutionPresentation(scoped,'t');assert.equal(JSON.stringify(scoped),scopedBefore,'scope selection never rewrites the ledger');
console.log('Task execution scope: paused parent/running child, permission wait, parallel children, consistent source/reply and root fallback passed');
