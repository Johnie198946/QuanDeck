import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const { chromium } = await import(process.env.QUANDECK_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.QUANDECK_UI_URL || 'http://127.0.0.1:4173';
const output = process.env.QUANDECK_UI_OUTPUT || 'output/material-recall';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true, channel:'chrome'});
try {
  const context = await browser.newContext({viewport:{width:1280,height:900},timezoneId:'Asia/Shanghai',locale:'zh-CN'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  page.setDefaultTimeout(8000);
  await page.clock.setFixedTime(new Date('2026-10-09T09:30:00+08:00'));
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.getByRole('region',{name:'任务管理',exact:true}).waitFor();
  const contact=process.env.QUANDECK_UI_FIXTURE_CONTACT || '林同事';
  const asking='向'+contact+'索取试点数据';
  const projectId = await page.evaluate(async ({asking,contact}) => {
    const { localDataSource: api } = await import('/src/data/repository.ts');
    if (window.quandeckDesktop || (await api.listProjects()).length) throw Error('Requires an empty test profile');
    const created = await api.createProject({name:'TokenOps',timeZone:'Asia/Shanghai'});
    if (!created.ok || !created.projectId) throw Error(created.message);
    const {projectId}=created;
    const createdAt = '2026-10-01T09:00:00+08:00';
    const lines = [asking,'写 TokenOps 主打材料','预订周末餐厅','向采购要预算清单'];
    const base = {id:'trial-notes',title:'产品周记',body:lines.join('\n'),createdAt,updatedAt:createdAt,revision:1,attachments:[],expansions:[],history:[]};
    const todos = lines.map((text,i)=>({text,lineIndex:i,id:'item-'+i,createdAt,dueAt:'2026-10-09T12:00:00+08:00'}));
    todos[0].completedAt = '2026-10-05T17:00:00+08:00';
    todos[0].followup = {dueAt:'2026-10-09T09:00:00+08:00',note:contact+'正在整理使用数据'};
    todos[3].completedAt = '2026-10-03T12:00:00Z';
    const projectQuotes=[{id:'filing',projectId,lineIndex:3,text:lines[3],at:createdAt}];
    localStorage.setItem('quandeck.personal-knowledge.v1',JSON.stringify({schema:1,notes:[{...base,todos,projectQuotes}],decisions:[]}));
    return projectId;
  },{asking,contact});
  await page.reload();
  const schedule = page.getByRole('region',{name:'日程',exact:true});
  const rows = schedule.getByRole('list',{name:'日程事项'}).locator(':scope > li');
  const row = title => rows.filter({has:page.getByText(title,{exact:true})});
  const writing = '写 TokenOps 主打材料';
  await row(writing).waitFor();
  assert.equal(await row(writing).locator('.qh-materials').count(),0);
  await row('跟进 · '+asking).getByRole('button',{name:'记下收到的材料'}).click();
  const receipt = page.getByRole('dialog',{name:'记下收到的材料'});
  const name = '试点前后对比表（已核对）';
  const url = 'https://example.com/trial-comparison';
  await receipt.getByLabel('结果说明').fill(name);
  await receipt.locator('summary').filter({hasText:'材料与用途'}).click();
  await receipt.getByLabel('材料链接（可选）').fill(url);
  await receipt.getByLabel('用在哪个项目（可选）').selectOption(projectId).catch(async error=>{console.error('project',projectId,await receipt.locator('select').innerHTML());throw error});
  await receipt.getByLabel('准备用来做什么（可选）').fill('TokenOps 主打材料');
  await receipt.getByLabel('添加材料文件').setInputFiles({name:'试点结果.txt',mimeType:'text/plain',buffer:Buffer.from('两组对照数据已确认')});
  await receipt.getByRole('button',{name:'移除 试点结果.txt'}).waitFor();
  const second = await page.context().newPage();
  await second.clock.setFixedTime(new Date('2026-10-09T09:30:00+08:00'));
  await second.goto(origin,{waitUntil:'networkidle'});
  await second.getByRole('button',{name:'记下收到的材料'}).first().click();
  const older = second.getByRole('dialog',{name:'记下收到的材料'});
  await older.getByRole('button',{name:'移除 试点结果.txt'}).waitFor();
  await page.evaluate(() => {
    void navigator.locks.request('quandeck.personal-knowledge.v1',()=>new Promise(resolve=>{window.releaseTestWrite=resolve}));
  });
  await page.waitForFunction(()=>typeof window.releaseTestWrite==='function');
  await receipt.getByRole('button',{name:'保存并完成日程',exact:true}).click();
  await page.waitForFunction(async ()=>(await navigator.locks.query()).pending.some(l=>l.name==='quandeck.personal-knowledge.v1'));
  await older.getByLabel('准备用来做什么（可选）').fill('下一稿继续编写');
  await page.evaluate(()=>window.releaseTestWrite());
  await receipt.waitFor({state:'hidden'});
  assert(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('quandeck.agenda-outcome-draft.v1.')).some(k=>JSON.parse(localStorage[k]).purpose==='下一稿继续编写')));
  await older.getByRole('button',{name:'移除 试点结果.txt'}).click();
  await older.getByRole('button',{name:'移除 试点结果.txt'}).waitFor({state:'hidden'});
  await second.close();
  await row('跟进 · '+asking).waitFor({state:'hidden'});
  await row(writing).locator('summary').filter({hasText:name}).waitFor();
  assert.equal(await row('预订周末餐厅').locator('.qh-materials').count(),0);
  await page.reload();
  const writingRow = row(writing);
  await writingRow.locator('.qh-materials > summary').click();
  assert.equal(await writingRow.getByRole('link',{name:'打开材料'}).getAttribute('href'),url);
  await writingRow.getByRole('button',{name:'用于此任务',exact:true}).click();
  await writingRow.getByRole('button',{name:'已用于此任务',exact:true}).waitFor();
  await writingRow.locator('.qh-receipt-files summary').click();
  await writingRow.getByText('两组对照数据已确认',{exact:true}).waitFor();
  await schedule.screenshot({path:path.join(output,'material-on-task.png')});
  const nav=page.getByRole('navigation',{name:'主导航'});
  await writingRow.getByRole('button',{name:'来源 · '+asking}).click();
  assert.equal(await page.getByRole('textbox',{name:'笔记标题'}).inputValue(),'产品周记');
  await nav.getByRole('button',{name:'首页',exact:true}).click();
  await schedule.getByRole('button',{name:/成果库/}).click();
  const outcomes=schedule.getByRole('region',{name:'日程结果'});
  await outcomes.getByRole('button',{name:/待补结果/}).click();
  await outcomes.getByRole('searchbox').fill('TokenOps');
  await outcomes.getByText('向采购要预算清单',{exact:true}).waitFor();
  await outcomes.getByRole('button',{name:/有材料/}).click();
  await outcomes.getByText(name,{exact:true}).waitFor();
  const board = page.getByRole('region',{name:'任务管理',exact:true});
  await board.getByRole('button',{name:'任务看板',exact:true}).click();
  await board.getByLabel('看板项目').selectOption(projectId);
  await board.getByRole('button',{name:'新建任务',exact:true}).click();
  const title = page.getByRole('textbox',{name:'新任务名称'});
  await title.fill('撰写 TokenOps 主打材料初稿');
  await title.press('Enter');
  await title.waitFor({state:'hidden'});
  await nav.getByRole('button',{name:'首页',exact:true}).click();
  await board.getByRole('button',{name:'任务看板',exact:true}).click();
  await board.getByRole('button',{name:'查看任务 撰写 TokenOps 主打材料初稿'}).click();
  const detail = page.getByRole('dialog');
  await detail.locator('.qh-materials > summary').filter({hasText:name}).waitFor();
  await detail.getByRole('button',{name:'打开任务'}).click();
  const materials=page.getByRole('region',{name:'可复用的材料'});
  await page.getByRole('region',{name:'待补材料'}).getByText('向采购要预算清单').waitFor();
  await materials.getByText(name,{exact:true}).first().waitFor();
  assert.equal(await materials.getByRole('link',{name:'打开材料'}).first().getAttribute('href'),url);
  await materials.getByRole('button',{name:'用于此任务',exact:true}).click();
  await materials.getByRole('button',{name:'已用于此任务',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'material-on-project.png')});
  await nav.getByRole('button',{name:'首页',exact:true}).click();
  await schedule.getByRole('button',{name:/成果库/}).click();
  await outcomes.getByRole('button',{name:/已引用/}).click();
  await outcomes.getByRole('searchbox').fill('主打材料初稿');
  const saved=outcomes.locator('.qh-shelf-item').filter({hasText:name});
  await saved.locator('.qh-shelf-trail').getByRole('button',{name:asking,exact:true}).waitFor();
  await saved.getByRole('button',{name:writing, exact:true}).waitFor();
  await saved.getByRole('button',{name:'撰写 TokenOps 主打材料初稿',exact:true}).waitFor();
  await saved.locator('.qh-receipt-files summary').click();
  await saved.getByText('两组对照数据已确认',{exact:true}).waitFor();
  await schedule.screenshot({path:path.join(output,'material-shelf.png')});
  await page.reload();
  await schedule.getByRole('button',{name:/成果库/}).click();
  await outcomes.getByRole('button',{name:/已引用/}).click();
  await saved.getByRole('button',{name:'撰写 TokenOps 主打材料初稿',exact:true}).click();
  await materials.getByRole('button',{name:'已用于此任务',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  console.log('PASS: received outcome survives reload; related personal and new project tasks recall it; unrelated task stays quiet; original note, source link and project search work.');
} finally { await browser.close(); }
