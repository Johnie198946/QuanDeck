import assert from 'node:assert/strict';
import { createSampleSnapshot } from '../src/data/fixtures';
import { completedResults, methodFor, taskOverviewRows } from '../src/data/results';
import { latestAttempt } from '../src/data/orchestration';
import { SampleWorkdeckDataSource } from '../src/data/repository';

async function run() {
  const snap = createSampleSnapshot();
  const o = snap.orchestrations!['task-a'];
  const done = Object.values(o.items).find(item => item.status === 'done' && item.source)!;
  const running = Object.values(o.items).find(item => item.status === 'running')!;
  const completed = completedResults(snap, 'task-a', null);
  assert(completed.length > 0);
  assert(completed.every(record => o.items[record.itemId!].status === 'done'));
  assert(!completed.some(record => record.itemId === running.id));
  const scoped = completedResults(snap, 'task-a', done.id);
  assert.equal(scoped.length, 1);
  assert.equal(scoped[0].attemptId, latestAttempt(o, done)!.id);

  // A retry without its own reply must never relabel an earlier result as the new attempt.
  const originalAttempt = latestAttempt(o, done)!;
  o.attempts['retry-empty'] = { ...originalAttempt, id: 'retry-empty', rounds: [] };
  done.attemptIds.push('retry-empty');
  assert.equal(completedResults(snap, 'task-a', done.id).length, 0);

  const method = methodFor(snap, 'task-a', done);
  assert.equal(method.adopted, true);
  assert(method.doc!.sections.every(section => section.lines.every(line => done.source!.lineIds.includes(line.id))));
  done.source!.version = 42;
  assert.equal(methodFor(snap, 'task-a', done).doc, null);
  assert.equal(methodFor(snap, 'task-a', done).unavailableVersion, 42);
  assert.equal(methodFor({ ...snap, ideaPlans: undefined }, 'task-a', null).plan, null);
  done.source!.version = 1;
  done.source!.planId = 'missing-source-plan';
  assert.equal(methodFor(snap, 'task-a', done).plan, null);
  assert.equal(methodFor(snap, 'task-a', done).doc, null);
  assert.equal(methodFor(snap, 'task-a', done).unavailableVersion, 1);
  const mismatched = createSampleSnapshot();
  const mismatchedItem = Object.values(mismatched.orchestrations!['task-a'].items).find(item => item.source)!;
  mismatched.ideaPlans!['plan-task-a'].draftVersion = 2;
  mismatchedItem.source!.version = 2;
  assert.equal(methodFor(mismatched, 'task-a', mismatchedItem).doc, null, 'an adopted task version must never resolve to an unadopted draft with the same number');
  assert.equal(methodFor(mismatched, 'task-a', mismatchedItem).conclusions.length, 0);

  const finalSnap = createSampleSnapshot();
  const finalOrch = finalSnap.orchestrations!['task-a'];
  const finalMain = finalSnap.sessions[finalOrch.mainSessionId!];
  finalMain.status = 'archived';
  finalMain.rounds.push({ id: 'final-main-reply', at: '20:45', reply: '最终交付：全文搜索已验收，附接入说明。' });
  const external = finalSnap.sessions['ses-codex-terms'];
  external.taskId = 'task-a';
  finalSnap.tasks['task-a'].sessionIds.push(external.id, external.id);
  const finalDone = Object.values(finalOrch.items).find(item => item.status === 'done' && latestAttempt(finalOrch, item)?.sessionId !== finalMain.id)!;
  const childAttempt = latestAttempt(finalOrch, finalDone)!;
  const childSessionId = childAttempt.sessionId!;
  finalSnap.sessions[childSessionId] = { ...structuredClone(finalMain), id: childSessionId };
  finalSnap.tasks['task-a'].sessionIds.push(childSessionId);
  const finalReports = completedResults(finalSnap, 'task-a', null);
  assert.equal(finalReports.filter(report => report.id === finalMain.id).length, 1);
  assert.equal(finalReports.filter(report => report.id === external.id).length, 1);
  assert.equal(finalReports.filter(report => report.id === childSessionId).length, 0);
  assert.equal(finalReports.filter(report => report.attemptId === childAttempt.id).length, 1);
  assert(completedResults(finalSnap, 'task-a', finalDone.id).every(report => !!report.itemId));
  childAttempt.sessionId = finalMain.id;
  assert.equal(completedResults(finalSnap, 'task-a', null).filter(report => report.id === finalMain.id).length, 1);

  const reviewSnap = createSampleSnapshot();
  Object.values(reviewSnap.orchestrations!['task-a'].items).forEach(item => { item.status = 'done'; });
  const review = taskOverviewRows(reviewSnap).find(row => row.task.id === 'task-a')!;
  assert.equal(review.status, 'review');
  assert.equal(review.waiting, true);
  assert.equal(review.running, false);
  reviewSnap.tasks['task-a'].completion = { reason: 'manual', at: '20:46' };
  assert.equal(taskOverviewRows(reviewSnap).find(row => row.task.id === 'task-a')!.waiting, false);

  const source = new SampleWorkdeckDataSource();
  const before = await source.load();
  const task = before.tasks['task-d'];
  const originalTask = structuredClone(task);
  const blockCount = before.journal.blocks.length;
  const planId = await source.ensureTaskPlan(task.id);
  assert.equal(await source.ensureTaskPlan(task.id), planId);
  const after = await source.load();
  assert.deepEqual(after.tasks[task.id], originalTask);
  assert.equal(after.journal.blocks.length, blockCount);
  assert.equal(Object.values(after.ideaPlans!).filter(plan => plan.taskId === task.id).length, 1);
  assert.equal(after.ideaPlans![planId].adopted, null);
  assert.equal(after.ideaPlans![planId].discussion!.conclusions.length, 0);
  await assert.rejects(source.ensureTaskPlan('missing-task'));
  await source.recordDiscussionConclusion(planId, 'root', { summary: '先梳理当天收获，再形成明日行动。', confirmed: ['整理今天三个收获'], open: [] });
  let planSnapshot = await source.load();
  const firstConclusion = planSnapshot.ideaPlans![planId].discussion!.conclusions.at(-1)!;
  await source.adoptDiscussionConclusion(planId, firstConclusion.id);
  await source.generateDrafts(planId);
  assert.equal((await source.addDraftsToTasks(planId)).ok, true, 'an existing task can create its first subtree');
  planSnapshot = await source.load();
  const adoptedPlan = planSnapshot.ideaPlans![planId];
  assert.equal(adoptedPlan.draftVersion, 2);
  assert.equal(adoptedPlan.adopted!.version, 1);
  assert.equal(adoptedPlan.adopted!.draftVersion, 2);
  assert.deepEqual(adoptedPlan.adopted!.conclusionIds, [firstConclusion.id]);
  assert.equal(methodFor(planSnapshot, task.id, null).conclusions[0]?.summary, firstConclusion.summary);
  const child = Object.values(planSnapshot.orchestrations![task.id].items)[0];
  assert.equal(methodFor(planSnapshot, task.id, child).conclusions[0]?.id, firstConclusion.id);

  await source.recordDiscussionConclusion(planId, 'root', { summary: '新增周复盘步骤。', confirmed: ['准备下周目标'], open: [] });
  planSnapshot = await source.load();
  const laterConclusion = planSnapshot.ideaPlans![planId].discussion!.conclusions.at(-1)!;
  await source.adoptDiscussionConclusion(planId, laterConclusion.id);
  planSnapshot = await source.load();
  assert.equal(planSnapshot.ideaPlans![planId].draftVersion, 3);
  assert.deepEqual(methodFor(planSnapshot, task.id, child).conclusions.map(conclusion => conclusion.id), [firstConclusion.id], 'newly adopted draft conclusions cannot replace historical task method provenance');
  const unmappedLegacy = structuredClone(planSnapshot);
  delete unmappedLegacy.ideaPlans![planId].adopted!.draftVersion;
  delete unmappedLegacy.ideaPlans![planId].adopted!.conclusionIds;
  assert.equal(methodFor(unmappedLegacy, task.id, child).conclusions.length, 0, 'legacy unequal documents have no proven conclusion mapping');
  unmappedLegacy.ideaPlans![planId].draft = structuredClone(unmappedLegacy.ideaPlans![planId].adopted!.doc);
  unmappedLegacy.ideaPlans![planId].draftVersion = 2;
  assert.equal(methodFor(unmappedLegacy, task.id, child).conclusions.length, 0, 'even identical legacy documents cannot prove the historical conclusion identity');
  assert(methodFor(unmappedLegacy, task.id, child).doc, 'legacy method body remains visible without guessing its conclusion mapping');
  console.log('results: exact attempt/source provenance, coordinator and merged-session reports, deduplication, branch isolation, missing methods, review queue, idempotent analysis');
}
run().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
