import assert from 'node:assert/strict';
import { parseDiscussionResponse, newConfirmationDraft, confirmationMessage } from '../src/data/discussionPresentation';
import { discussionSummary, discussionDetail } from '../src/data/discussionSnippets';

const value = { summary: '**先确认日期**，再整理攻略。', confirmed: ['目的地：曼谷和芭提雅', '预算：2 万元'], open: ['从哪里出发？'] };
const raw = '<quandeck-conclusion>' + JSON.stringify(value) + '</quandeck-conclusion>';
const parsed = parseDiscussionResponse(raw);
assert.equal(parsed.content, '');
assert.deepEqual(parsed.conclusion?.proposals, value.confirmed);
assert.equal(parsed.malformed, false);
const draft = newConfirmationDraft(parsed.conclusion!);
assert.equal(confirmationMessage(parsed.conclusion!, draft), '', 'AI proposals are never preselected');
draft.proposals[0] = '目的地：只去曼谷';
draft.selected = [0]; draft.answers[0] = '上海'; draft.extra = '希望节奏轻松';
const message = confirmationMessage(parsed.conclusion!, draft);
assert.match(message, /只去曼谷/); assert.doesNotMatch(message, /芭提雅|预算/); assert.match(message, /从哪里出发？\n上海/); assert.match(message, /希望节奏轻松/);
assert.equal(parseDiscussionResponse('```json\n' + JSON.stringify(value) + '\n```').conclusion?.summary, value.summary);
assert.equal(parseDiscussionResponse(raw.replace('}', ',}')).malformed, true);
assert.equal(parseDiscussionResponse(`“${raw}”`).content, '');
const submission = '<quandeck-submission>' + JSON.stringify({schemaVersion:'quandeck.runtime.v1',idempotencyKey:'travel-guide',binding:{projectId:'p',taskId:'t',runId:'r',contextPackageId:'c',taskVersion:1,specRevision:1,claimEpoch:1},kind:'result',payload:{title:'曼谷与芭提雅攻略',body:'# 行程重点\n\n周四：老街漫步。',sourceIds:[],unresolved:[],nextSteps:[]}}) + '</quandeck-submission>';
assert.equal(parseDiscussionResponse(submission).submission?.kind,'result');
assert.equal(parseDiscussionResponse(submission).conclusion,undefined,'a candidate result must not become user confirmation');
assert.equal(discussionSummary(submission),'曼谷与芭提雅攻略');
assert.equal(discussionDetail(submission),'# 行程重点\n\n周四：老街漫步。');
assert.equal(parseDiscussionResponse(submission.replace('"taskVersion":1','"taskVersion":0')).malformed,true);
assert.equal(parseDiscussionResponse('<quandeck-submission>{"payload":').content,'');
assert.equal(parseDiscussionResponse('<quandeck-conclusion>{"summary":').content, '');
assert.equal(parseDiscussionResponse('普通回复\n- 保留格式').content, '普通回复\n- 保留格式');
const rich = parseDiscussionResponse('<quandeck-conclusion>' + JSON.stringify({ ...value, cards: [{title:'行程',body:'每日安排'}], charts: [{title:'比较',type:'bar',labels:['A','B'],series:[{label:'价格',values:[10,20]}]}, {title:'无效',type:'line',labels:['A','B'],series:[{label:'价格',values:[10]}]}], attachments: [{name:'攻略.docx',path:'攻略.docx'}, {name:'不完整'}] }) + '</quandeck-conclusion>').conclusion!;
assert.equal(rich.cards.length, 1); assert.equal(rich.charts.length, 1); assert.equal(rich.attachments.length, 1);
assert.equal(parseDiscussionResponse('<quandeck-conclusion>{"summary":"不可自动确认","confirmed":[true],"open":[]}</quandeck-conclusion>').malformed, true);
console.log('Discussion presentation: protocol, malformed replies, explicit edited confirmation and rich content passed');
