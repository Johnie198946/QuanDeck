import assert from 'node:assert/strict';
import { LocalWorkdeckDataSource } from '../src/data/repository';
import { createRuntimeDataSource } from '../src/data/runtimeDataSource';
import { buildContextPackage, reconcileCollaborationEdits, taskKey } from '../src/data/collaboration';
import { approveDirection, readPlanTasks } from '../src/data/projectWorkflow';
import { isGeneratedDiscussionSummary, visibleDirectionSections, directionReadingSections } from '../src/data/discussionAuthority';
import type { RuntimeDriver, RuntimeRunInput } from '../src/data/runtimeContracts';

const values = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => values.set(key, value), removeItem: (key: string) => values.delete(key) } });

async function run() {
  const source = new LocalWorkdeckDataSource();
  const projectId = (await source.createProject({ name: 'Discussion authority boundary' })).projectId!;
  await source.registerAgent({ id: 'codex', name: 'Codex', short: 'Codex', color: '#111111' });
  const taskId = (await source.createTaskWithAttachments('核对路线', [], projectId)).taskId!;
  const planId = await source.ensureTaskPlan(taskId);
  const summary = '本轮仅提交方向与执行结构，不启动业务任务';
  const proposal = '使用可核对来源生成路线表';
  assert((await source.recordDiscussionConclusion(planId, 'root', {
    summary, confirmed: [proposal], open: [],
    outline: [{ id: 's-method', title: '执行方法', kind: 'key', lines: [{ id: 'route-method', text: '对比两个独立路线来源', state: 'fixed' }] }],
    tasks: readPlanTasks([{ key: 'route', title: '查询机场路线', expected: '有证据的路线表', deps: [], owner: 'agent', phase: '执行' }]),
  })).ok);
  let snapshot = await source.load();
  const conclusion = snapshot.ideaPlans![planId].discussion!.conclusions.at(-1)!;
  assert((await source.approvePlan(planId, conclusion.id, projectId)).ok);
  snapshot = await source.load();
  const plan = snapshot.ideaPlans![planId];
  assert.equal(plan.discussion!.conclusions.at(-1)!.summary, summary, 'narrative remains in immutable discussion history');
  assert(!plan.adopted!.doc.sections.flatMap(section => section.lines).some(line => line.text === summary));
  assert(!snapshot.collaboration!.decisions.some(decision => decision.text === summary), 'approving direction never invents a human instruction from the round summary');
  assert(snapshot.collaboration!.decisions.some(decision => decision.text === proposal && decision.authority === 'confirmed'), 'explicitly adopted proposals retain their authority');
  assert(plan.adopted!.doc.sections.flatMap(section => section.lines).some(line => line.id === 'route-method'), 'structured execution outline is still adopted');
  const outlineOnly = structuredClone(plan);
  outlineOnly.adopted = null;
  outlineOnly.draft.sections = outlineOnly.draft.sections.filter(section => section.id !== 's-direction');
  const outlineConclusion = outlineOnly.discussion!.conclusions[0];
  outlineConclusion.adopted = false; outlineConclusion.confirmed = []; outlineConclusion.proposed = [];
  approveDirection(snapshot, outlineOnly, outlineConclusion);
  assert(!outlineOnly.draft.sections.some(section => section.id === 's-direction'), 'outline-only approval never creates an empty confirmed-direction group');
  const duplicateProposal = structuredClone(outlineOnly);
  duplicateProposal.adopted = null;
  const duplicateConclusion = duplicateProposal.discussion!.conclusions[0];
  duplicateConclusion.adopted = false; duplicateConclusion.proposed = ['对比两个独立路线来源'];
  approveDirection(snapshot, duplicateProposal, duplicateConclusion);
  assert(!duplicateProposal.draft.sections.some(section => section.id === 's-direction'), 'an already-present adopted proposal does not create an empty duplicate group');
  const oldEmpty = structuredClone(outlineOnly.draft);
  oldEmpty.sections.push({ id: 's-direction', title: '已确认方向', kind: 'key', lines: [] });
  oldEmpty.sections.push({ id: 'custom-empty', title: '需要补充的材料', kind: 'body', lines: [] });
  const oldEmptyBefore = JSON.stringify(oldEmpty);
  assert(!visibleDirectionSections(oldEmpty).some(section => section.id === 's-direction'));
  assert(visibleDirectionSections(oldEmpty).some(section => section.id === 'custom-empty'), 'real empty outline sections remain visible');
  assert.equal(JSON.stringify(oldEmpty), oldEmptyBefore, 'reading projection keeps legacy snapshots unchanged');
  oldEmpty.sections.find(section => section.id === 's-direction')!.title = '我的待办方向';
  assert(visibleDirectionSections(oldEmpty).some(section => section.id === 's-direction'), 'renamed user section remains visible');
  assert(visibleDirectionSections(plan.adopted!.doc).some(section => section.id === 's-direction'), 'a nonempty confirmed direction remains visible');
  const itemId = Object.keys(snapshot.orchestrations![taskId].items)[0];
  const key = taskKey(taskId, itemId);

  // Reproduce the exact provenance generated by older approval code. Neither the
  // stored direction nor its decision history is rewritten during compatibility.
  const oldLineId = `${conclusion.id}-direction-0`;
  source.mutateRuntimeProject(projectId, draft => {
    const current = draft.ideaPlans![planId];
    for (const doc of [current.draft, current.adopted!.doc]) {
      const section = doc.sections.find(section => section.id === 's-direction')!;
      // Older builds reserved index 0 for summary and 1 for first proposal.
      for (const line of section.lines) if (line.id === oldLineId) line.id = `${conclusion.id}-direction-1`;
      section.lines.unshift({ id: oldLineId, text: summary, state: 'fixed', userEdited: true });
    }
    for (const decision of draft.collaboration!.decisions) if (decision.decisionId === `plan:${planId}:line:${oldLineId}`) decision.decisionId = `plan:${planId}:line:${conclusion.id}-direction-1`;
    draft.collaboration!.decisions.push({ id: 'legacy-summary-v1', decisionId: `plan:${planId}:line:${oldLineId}`, revision: 1, taskKey: taskId, text: summary, kind: 'constraint', authority: 'confirmed', at: draft.now, source: 'human' });
  });
  snapshot = await source.load();
  const before = JSON.stringify({ plans: snapshot.ideaPlans, decisions: snapshot.collaboration!.decisions });
  const context = buildContextPackage(snapshot, key);
  assert(!context.constraints.some(constraint => constraint.text === summary), 'old generated narrative is not a binding condition in new execution contexts');
  assert(context.constraints.some(constraint => constraint.text === proposal));
  assert.equal(JSON.stringify({ plans: snapshot.ideaPlans, decisions: snapshot.collaboration!.decisions }), before, 'legacy compatibility is read-only');

  const calls: RuntimeRunInput[] = [];
  const driver: RuntimeDriver = { subscribe: () => () => {}, scan: async () => [], control: async () => {}, listRuns: () => [], run: async input => { calls.push(input); return { runId: 'authority-run', sessionId: 'authority-source', connectionId: input.connectionId, acceptedAt: new Date().toISOString() }; } };
  const runtime = createRuntimeDataSource(source, driver);
  await runtime.bindRuntimeConnection('codex', { tool: 'codex', connectionId: 'authority', projectPath: '/authority-fixture' });
  const dispatched = await runtime.dispatchProjectTask(projectId, taskId, 'codex', itemId);
  assert(dispatched.ok, dispatched.message);
  assert.equal(calls.length, 1);
  assert(!calls[0].prompt.includes(summary), 'the actual source request omits legacy phase narrative in both fixed context and adopted execution method');
  assert(calls[0].prompt.includes(proposal) && calls[0].prompt.includes('对比两个独立路线来源'));
  runtime.dispose();

  assert((await source.recordPlanConfirmation(planId, conclusion.id, [summary], projectId)).ok);
  const confirmedByUser = await source.load();
  assert(buildContextPackage(confirmedByUser, key).constraints.some(constraint => constraint.text === summary && constraint.id !== 'legacy-summary-v1'), 'explicit user confirmation is recorded separately instead of deduplicating against an old generated summary');
  const count = confirmedByUser.collaboration!.decisions.filter(decision => decision.text === summary).length;
  await source.recordPlanConfirmation(planId, conclusion.id, [summary], projectId);
  assert.equal((await source.load()).collaboration!.decisions.filter(decision => decision.text === summary).length, count, 'repeating the actual user confirmation remains idempotent');

  // Authority is identified by provenance, not by prohibitive words.
  const explicit = structuredClone(snapshot);
  explicit.collaboration!.decisions.push({ id: 'explicit-v1', decisionId: 'user-explicit-condition', revision: 1, taskKey: taskId, text: summary, kind: 'constraint', authority: 'confirmed', at: explicit.now, source: 'human' });
  assert(buildContextPackage(explicit, key).constraints.some(constraint => constraint.id === 'explicit-v1'), 'a separately confirmed user condition with identical wording remains binding');
  const changed = structuredClone(plan);
  assert(!isGeneratedDiscussionSummary(changed, oldLineId, '仅先开发测试环境'), 'user-edited generated lines are retained');
  const sameProposal = structuredClone(plan);
  const sameConclusion = sameProposal.discussion!.conclusions[0];
  sameConclusion.proposed = [summary];
  assert(!isGeneratedDiscussionSummary(sameProposal, oldLineId, summary), 'an explicit adopted proposal is not removed merely because its text matches the summary');
  const confirmedDespiteEmptyProposals = structuredClone(plan);
  confirmedDespiteEmptyProposals.discussion!.conclusions[0].proposed = [];
  confirmedDespiteEmptyProposals.discussion!.conclusions[0].confirmed = [summary];
  assert(!isGeneratedDiscussionSummary(confirmedDespiteEmptyProposals, oldLineId, summary));

  // A new direction approval may retain old lines, but cannot promote the
  // generated old summary again. All genuine conditions still bridge normally.
  const legacyUnbridged = structuredClone(snapshot);
  legacyUnbridged.collaboration!.decisions = legacyUnbridged.collaboration!.decisions.filter(decision => decision.id !== 'legacy-summary-v1');
  const adoptedAgain = structuredClone(legacyUnbridged);
  adoptedAgain.ideaPlans![planId].adopted!.version++;
  reconcileCollaborationEdits(legacyUnbridged, adoptedAgain);
  assert(!adoptedAgain.collaboration!.decisions.some(decision => decision.text === summary), 'a later adoption cannot re-promote a legacy generated summary');
  const userEdited = structuredClone(adoptedAgain);
  const editedLine = userEdited.ideaPlans![planId].draft.sections.flatMap(section => section.lines).find(line => line.id === oldLineId)!;
  editedLine.text = '仅先开发测试环境';
  reconcileCollaborationEdits(adoptedAgain, userEdited);
  assert(userEdited.collaboration!.decisions.some(decision => decision.text === editedLine.text && decision.authority === 'confirmed'), 'an actual edit to the old line still creates a user condition');
  console.log('discussion authority: summary/proposal boundary, legacy read-only projection, real source prompt, explicit-user preservation');
}
run().catch(error => { console.error(error); process.exitCode = 1; });

