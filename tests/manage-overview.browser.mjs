  await inspector.getByRole('button',{name:'保存批注'}).click();
  await inspector.getByText('批注已保存').waitFor();
  await plan.getByRole('button',{name:'智能路由页面',exact:true}).click();
  await inspector.getByText(routingNote,{exact:true}).first().waitFor();
  assert.equal(await inspector.getByText(monitoringNote,{exact:true}).count(),0);
  await page.screenshot({path:path.join(output,'overview-discussion.png')});
  await inspectorNav.getByRole('button',{name:/相关资料/}).click();
  await inspector.getByRole('button',{name:'移除任务附件 '+fileName}).waitFor();
