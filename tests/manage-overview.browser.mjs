  await plan.getByRole('button',{name:'智能路由页面',exact:true}).click();
  await inspector.getByRole('heading',{name:'智能路由页面'}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'page fits a narrow viewport');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:path.join(output,'overview-narrow.png'),fullPage:true});
  await page.setViewportSize({width:320,height:780});
  await inspectorNav.getByRole('button',{name:/讨论/}).click();
  await inspector.getByText(routingNote,{exact:true}).first().waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'discussion wraps in 320px');
