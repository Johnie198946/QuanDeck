  await inspectorNav.getByRole('button',{name:'详情',exact:true}).click();
  await inspectorNav.getByRole('button',{name:'讨论'}).click();
  assert.equal(await inspector.getByRole('textbox',{name:/我的批注/}).inputValue(),routingNote);
  await inspector.getByRole('button',{name:'保存批注'}).click();
  await inspector.getByText('批注已保存').waitFor();
  await inspector.getByText(routingNote,{exact:true}).first().waitFor();
  await inspectorNav.getByRole('button',{name:/相关资料/}).click();
